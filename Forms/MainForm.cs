    private bool crashNoticeShown;

    /// <summary>Das Hilfsprogramm ist abgestürzt oder hing (Thread der Verbindung): Die Anzeige wird geleert, und PDFlight bietet an, die
    /// Datei neu zu laden – das startet ein neues Hilfsprogramm. Offene Formulareingaben sind verloren.</summary>
    private void SandboxClient_Crashed(object? sender, SandboxCrashedException e)
    {
        if (IsHandleCreated && !IsDisposed) { BeginInvoke(() => OnViewerCrashed()); }
    }

    private void OnViewerCrashed()
    {
        if (crashNoticeShown || IsDisposed || document == null) { return; }
        var page = ClampedCurrentPage();
        ShowDocument(null);
        if (currentFile == null) { return; }
        crashNoticeShown = true;
        try
        {
            if (TaskDlg.ConfirmTaskDlg(Handle, Lng.T("Die PDF-Darstellung wurde unerwartet beendet."), Lng.T("Die Datei neu laden?")) && currentFile != null)
            {
                LoadPdf(currentFile.FullName, page);
            }
        }
        finally { crashNoticeShown = false; }
    }

    private void MainForm_FormClosed(object? sender, FormClosedEventArgs e)
    {
        SandboxClient.Crashed -= SandboxClient_Crashed;
    }

