    private void MoveCopyDialog(bool copy)
    {
        if (currentFile == null) { return; }
        Cursor.Current = Cursors.WaitCursor;
        settings.ReloadSharedLists(); // Ziel-/Zuletzt-Listen anderer Instanzen übernehmen
        var startFolder = settings.TargetFolders.FirstOrDefault(f => !string.IsNullOrEmpty(f) && Directory.Exists(f)) ?? string.Empty;
        var jumpToLastUsed = settings.RecentFolders.Count > 0 // der Dialog springt immer zum zuletzt verwendeten Ordner (Option entfallen 19.09.2026)
            && Directory.Exists(settings.RecentFolders[0]) // sonst meldet der Dialog bei jedem Öffnen einen fehlenden Pfad
            && !string.Equals(startFolder, settings.RecentFolders[0], StringComparison.OrdinalIgnoreCase);

        using FolderSelectForm dialog = new(startFolder, copy, jumpToLastUsed);
        dialog.MaxRecent = settings.MaxRecentFolders;
        dialog.SetRecentFolders(settings.RecentFolders);
        dialog.SetTargetFolders(settings.TargetFolders.Where(f => !string.IsNullOrEmpty(f)));
        dialog.ShellTreePath = startFolder;

        var result = dialog.ShowDialog(this);
        // Einstellungen aus dem Dialog gelten unabhängig vom Ergebnis: Länge der Zuletzt-Liste, „Liste leeren“
        if (dialog.ClearRecentRequested) { settings.RecentFolders.Clear(); }
        else if (dialog.RecentTrimmed) { settings.RecentFolders = [.. dialog.RecentFolders]; } // Kürzung wurde im Dialog bestätigt
        if (dialog.ClearRecentRequested || dialog.RecentTrimmed || settings.MaxRecentFolders != dialog.MaxRecent)
        {
            settings.MaxRecentFolders = dialog.MaxRecent;
            settings.TrimRecentLists(); // eine kleinere Höchstzahl (bis hin zu 0) wirft überzählige Einträge sofort weg
            settings.Save();
        }
        if (dialog.EditTargetsRequested) // „Liste bearbeiten“: der Dialog hat sich geschlossen, jetzt die Einstellungen (Zielliste)
        {
            Cursor.Current = Cursors.Default;
            OpenSettings(SettingsForm.TabTargets);
            return;
        }
        if (result == DialogResult.OK)
        {
            var folder = dialog.ShellTreePath;
            if (string.IsNullOrEmpty(folder)) { return; }
            if (dialog.Add2Folderlist.Checked && !settings.TargetFolders.Any(f => string.Equals(f, folder, StringComparison.OrdinalIgnoreCase)))
            {
                settings.TargetFolders.Insert(0, folder);
                settings.Save();
            }
            MoveOrCopyTo(folder, copy);
        }
        Cursor.Current = Cursors.Default;
    }

    private void MoveOrCopyTo(string folder, bool copy)
    {
        if (currentFile == null) { return; }
        if (!Directory.Exists(folder))
        {
            TaskDlg.MsgTaskDlg(Handle, Lng.T("Der Zielordner existiert nicht."), folder, TaskDialogIcon.Warning);
            return;
        }
        if (string.Equals(Path.TrimEndingDirectorySeparator(folder), currentFile.DirectoryName, StringComparison.OrdinalIgnoreCase))
        {
            TaskDlg.MsgTaskDlg(Handle, Lng.T("Die Datei befindet sich bereits in diesem Ordner."), null, TaskDialogIcon.Information);
            return;
        }
        var destination = Path.Combine(folder, currentFile.Name);
        if (File.Exists(destination))
        {
            destination = AskReplaceOrRename(destination); // Ersetzen / name_n anlegen / Abbrechen (wie in PDFMover)
            if (destination == null) { return; }
        }
        try
        {
            settings.ReloadSharedLists(); // parallel laufende Instanzen nicht überschreiben
            if (copy)
            {
                File.Copy(currentFile.FullName, destination, true);
                statusPath.Text = Lng.T("Kopiert nach:") + " " + destination;
                AskWhichFileToShow(destination);
            }
            else
            {
                var sourceFolder = currentFile.DirectoryName;
                var sourcePath = currentFile.FullName;
                File.Move(currentFile.FullName, destination, true);
                RememberMoveForUndo(string.Format(Lng.T("Verschieben nach „{0}“"), new DirectoryInfo(folder).Name), sourcePath, destination);
                UpdateFilePaths(sourcePath, destination);
                LoadPdf(destination); // die verschobene Datei bleibt angezeigt — nun vom neuen Ort (wie in PDFMover)
                CheckForDuplicate(new FileInfo(destination));
                previousFolder = sourceFolder; // beim nächsten Blättern die Rückkehr in den bisherigen Ordner anbieten
                ShowSplash(Lng.T("Datei verschoben")); // das blitzschnelle Neuladen allein wäre leicht zu übersehen
            }
            settings.AddRecentFolder(folder);
            settings.Save();
            UpdateOneClickLabel(); // der zuletzt verwendete Ordner kann jetzt der 1-Klick-Ordner sein
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            TaskDlg.ErrTaskDlg(Handle, copy ? Lng.T("Kopieren fehlgeschlagen.") : Lng.T("Verschieben fehlgeschlagen."), ex);
        }
    }

    /// <summary>Zieldatei existiert bereits: Ersetzen, unter freiem name_n-Namen anlegen oder abbrechen (Dialog wie in PDFMover).
