    private SplashLabelForm? splashLabel;

    /// <summary>Zeigt eine Einblend-Meldung mittig über dem Viewer; splashTimer blendet sie nach der Anzeigedauer (Vorgabe 1 s) aus.
    /// atTop: knapp unter dem Oberrand wie der Vollbild-Hinweis von Chrome und Edge.</summary>
    private void ShowSplash(string text, int milliseconds = 1000, bool atTop = false)
    {
        splashTimer.Interval = milliseconds;
        splashLabel ??= new SplashLabelForm();
        splashLabel.SetMessage(text);
        var host = pageView.PointToScreen(Point.Empty);
        var size = splashLabel.PreferredSize;
        var top = atTop ? LogicalToDeviceUnits(48) : (pageView.Height - size.Height) / 3; // sonst im oberen Drittel: dort verdeckt sie kaum Inhalt und fällt trotzdem auf
        splashLabel.Location = new Point(host.X + (pageView.Width - size.Width) / 2, host.Y + top);
        splashLabel.Show(this);
        splashTimer.Stop(); // eine laufende Anzeige beginnt von vorn
        splashTimer.Start();
    }

    private void SplashTimer_Tick(object? sender, EventArgs e)
    {
        HideSplash();
    }

    private void HideSplash()
    {
        splashTimer.Stop();
        splashLabel?.Hide();
    }

    /// <summary>F11-Vollbild wie im Browser: randlos maximiert, Tool- und Statusleiste ausgeblendet; F11 oder gedrückt gehaltenes Esc
    /// beendet (s. <see cref="ExitFullScreenByEscape"/>). Beim Einschalten blendet es wie Chrome und Edge den Hinweis darauf ein.</summary>
    private void SetFullScreen(bool enable)
    {
        if (isFullScreen == enable) { return; }
        isFullScreen = enable;
        SuspendLayout();
        if (enable)
        {
            fullScreenPreviousState = WindowState;
            toolStrip.Visible = statusStrip.Visible = pnlPdfA.Visible = false;
            FormBorderStyle = FormBorderStyle.None;
            WindowState = FormWindowState.Normal;    // erzwingt die Neuberechnung, falls das Fenster bereits maximiert war
            WindowState = FormWindowState.Maximized; // randlos maximiert = echtes Vollbild inkl. Taskleiste
        }
        else
        {
            toolStrip.Visible = statusStrip.Visible = true;
            pnlPdfA.Visible = currentFile != null && PdfALocked;
            FormBorderStyle = FormBorderStyle.Sizable;
            WindowState = fullScreenPreviousState;
        }
        ResumeLayout();
        ApplyViewerIcons(); // Vollbild-Schaltfläche: ein bzw. aus
        btnFullScreen.ToolTipText = enable ? Lng.T("Vollbildmodus beenden (F11)") : Lng.T("PDF im Vollbildmodus anzeigen (F11)");
        if (enable) { ShowSplash(Lng.T("Zum Beenden des Vollbildmodus Esc drücken"), 3000, atTop: true); }
        else { HideSplash(); } // ein noch stehender Hinweis passte nicht mehr zur Fenstergröße
    }

