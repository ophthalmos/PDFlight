    private string? oneClickFolderShown; // der angezeigte 1-Klick-Ordner (voller Pfad); null = Label ausgeblendet

    /// <summary>Zeigt den 1-Klick-Ordner in der Statusleiste: den vollen Pfad — nur wenn der Platz
