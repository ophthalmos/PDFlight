    // zeichnet jede Seite in eine EMF in Druckerpixeln, abgespielt wird sie hier im Gerätekontext des Druckers – Lage und Größe auf dem
    // Bogen rechnet PrintLayout, genau wie die Vorschau im Druckdialog. Der Druck läuft in einem Hintergrund-Thread
    // (PrintDocument.Print blockiert), der UI-Thread bleibt frei.
    private PdfiumDocument? printingDocument;
    private PrintJob? printingJob;
    private int printNext; // Nummer des nächsten Bogens in printingJob.Pages

    /// <summary>Strg+P und „Drucken“: PDFlights Druckdialog mit Vorschau (wie in Edge); von dort aus auf Wunsch der von Windows.</summary>
    private async void PrintWithDialog()
    {
        if (ShownDocument is not { } doc || printingDocument != null) { return; }
        var copy = await CreatePrintCopyAsync(doc);
        if (copy == null) { return; }
        using PrintForm dialog = new(copy, Math.Max(1, ClampedCurrentPage()), string.IsNullOrEmpty(settings.LastPrinter) ? null : settings.LastPrinter);
        var result = dialog.ShowDialog(this);
        if (dialog.SystemDialogRequested) { await PrintWithSystemDialogAsync(copy); return; }
        if (result != DialogResult.OK || dialog.Job is not { } job) { copy.Dispose(); return; }
        settings.ReloadSharedLists();
        settings.LastPrinter = dialog.PrinterSettings.PrinterName;
        settings.Save();
        printDocument.PrinterSettings = dialog.PrinterSettings;
        printDocument.DefaultPageSettings.PaperSize = dialog.Paper ?? printDocument.DefaultPageSettings.PaperSize;
        printDocument.DefaultPageSettings.Color = dialog.InColor;
        await PrintAsync(copy, job);
    }

    /// <summary>Strg+Umschalt+P: gleich der Druckdialog von Windows (Drucker, Seitenbereich, Eigenschaften des Druckers).</summary>
    private async void PrintWithSystemDialog()
    {
        if (ShownDocument is not { } doc || printingDocument != null) { return; }
        if (await CreatePrintCopyAsync(doc) is { } copy) { await PrintWithSystemDialogAsync(copy); }
    }

    private async Task PrintWithSystemDialogAsync(PdfiumDocument copy)
    {
        var printerSettings = printDocument.PrinterSettings;
        printerSettings.MinimumPage = 1;
        printerSettings.MaximumPage = copy.PageCount;
        printerSettings.FromPage = 1;
        printerSettings.ToPage = copy.PageCount;
        printerSettings.PrintRange = System.Drawing.Printing.PrintRange.AllPages;
        printerSettings.PrintToFile = false;
        if (printDialog.ShowDialog(this) != DialogResult.OK) { copy.Dispose(); return; }
        var current = Math.Max(1, ClampedCurrentPage());
        var (from, to) = printerSettings.PrintRange switch
        {
            System.Drawing.Printing.PrintRange.SomePages => (Math.Clamp(printerSettings.FromPage, 1, copy.PageCount), Math.Clamp(printerSettings.ToPage, 1, copy.PageCount)),
            System.Drawing.Printing.PrintRange.CurrentPage => (current, current),
            _ => (1, copy.PageCount),
        };
        if (to < from) { (from, to) = (to, from); }
        await PrintAsync(copy, new PrintJob([.. Enumerable.Range(from - 1, to - from + 1)], PrintOrientation.Auto, PrintScaling.Fit, 100));
    }

    /// <summary>Druckkopie des angezeigten Dokuments (die Eingabe im Formularfeld vorher übernommen); null nach einer Fehlermeldung.</summary>
    private async Task<PdfiumDocument?> CreatePrintCopyAsync(PdfiumDocument doc)
    {
        await pageView.EndFormInputAsync();
        try { return await doc.CreatePrintCopyAsync(0, doc.PageCount - 1); }
        catch (InvalidOperationException ex)
        {
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Drucken fehlgeschlagen."), ex);
            return null;
        }
    }

    /// <summary>Druckt die Bögen des Auftrags auf dem Drucker aus printDocument und gibt die Druckkopie danach frei; false bei einem Fehler.</summary>
    private async Task<bool> PrintAsync(PdfiumDocument copy, PrintJob job)
    {
        if (printingDocument != null || job.Pages.Count == 0) { copy.Dispose(); return false; }
        printingDocument = copy;
        printingJob = job;
        btnPrint.Enabled = false;
        printDocument.DocumentName = Path.GetFileName(copy.Path);
        printDocument.PrintController = new System.Drawing.Printing.StandardPrintController(); // kein eigenes Fortschrittsfenster – die Statusleiste zeigt ihn
        try
        {
            await Task.Run(printDocument.Print);
            statusPath.Text = string.Format(Lng.T("{0} Seiten an „{1}“ gesendet."), job.Pages.Count, printDocument.PrinterSettings.PrinterName);
            return true;
        }
        catch (Exception ex) when (ex is System.Drawing.Printing.InvalidPrinterException or System.ComponentModel.Win32Exception or InvalidOperationException)
        {
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Drucken fehlgeschlagen."), ex);
            return false;
        }
        finally
        {
            copy.Dispose();
            printingDocument = null;
            printingJob = null;
            btnPrint.Enabled = currentFile != null;
        }
    }

    private void PrintDocument_BeginPrint(object? sender, System.Drawing.Printing.PrintEventArgs e)
    {
        printNext = 0;
    }

    /// <summary>Hoch- oder Querformat je Bogen (läuft auf dem Druck-Thread).</summary>
    private void PrintDocument_QueryPageSettings(object? sender, System.Drawing.Printing.QueryPageSettingsEventArgs e)
    {
        if (printingDocument is not { } doc || printingJob is not { } job || printNext >= job.Pages.Count) { return; }
        e.PageSettings.Landscape = PrintLayout.IsLandscape(job.Orientation, doc.PageSizes[job.Pages[printNext]]);
    }

    /// <summary>Einen Bogen drucken (läuft auf dem Druck-Thread).</summary>
    private void PrintDocument_PrintPage(object? sender, System.Drawing.Printing.PrintPageEventArgs e)
    {
        if (printingDocument is not { } doc || printingJob is not { } job || e.Graphics is not { } graphics || printNext >= job.Pages.Count) { e.Cancel = true; return; }
        var page = job.Pages[printNext];
        var dc = graphics.GetHdc();
        try
        {
            // bedruckbarer Bereich in Gerätepixeln (bei Querformat schon gedreht); der Ursprung des Gerätekontexts liegt in seiner Ecke
            var width = NativePdfium.GetDeviceCaps(dc, NativePdfium.HorzRes);
            var height = NativePdfium.GetDeviceCaps(dc, NativePdfium.VertRes);
            var pixelsPerPoint = NativePdfium.GetDeviceCaps(dc, NativePdfium.LogPixelsX) / 72f;
            var target = Rectangle.Round(PrintLayout.Place(doc.PageSizes[page], new RectangleF(0, 0, width, height), pixelsPerPoint, job.Scaling, job.ScalePercent));
            if (target.Width > 0 && target.Height > 0)
            {
                var emf = doc.RenderEmfAsync(page, target.Width, target.Height).GetAwaiter().GetResult();
                NativePdfium.PlayMetafile(dc, emf, target);
            }
        }
        finally { graphics.ReleaseHdc(dc); }
        var printed = printNext + 1;
        var total = job.Pages.Count;
        BeginInvoke(() => statusPath.Text = string.Format(Lng.T("Drucke Seite {0} von {1}…"), printed, total));
        e.HasMorePages = ++printNext < job.Pages.Count;
    }

