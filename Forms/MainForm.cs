    private void MoveOrCopyTo(string folder, bool copy)
    {
        if (currentFile == null) { return; }
        if (!Directory.Exists(folder))
        {
            TaskDlg.MsgTaskDlg(Handle, Lng.T("Der Zielordner existiert nicht."), folder, TaskDialogIcon.Warning);
            return;
        }
        if (string.Equals(Path.TrimEndingDirectorySeparator(folder), currentFile.DirectoryName, StringComparison.OrdinalIgnoreCase))
        {
            TaskDlg.MsgTaskDlg(Handle, Lng.T("Die Datei befindet sich bereits in diesem Ordner."), null, TaskDialogIcon.Information);
            return;
        }
        var destination = Path.Combine(folder, currentFile.Name);
        if (File.Exists(destination))
        {
            destination = AskReplaceOrRename(destination); // Ersetzen / name_n anlegen / Abbrechen (wie in PDFMover)
            if (destination == null) { return; }
        }
        try
        {
            settings.ReloadSharedLists(); // parallel laufende Instanzen nicht überschreiben
            if (copy)
            {
                File.Copy(currentFile.FullName, destination, true);
                statusPath.Text = Lng.T("Kopiert nach:") + " " + destination;
                AskWhichFileToShow(destination);
            }
            else
            {
                var sourceFolder = currentFile.DirectoryName;
                var sourcePath = currentFile.FullName;
                File.Move(currentFile.FullName, destination, true);
                RememberMoveForUndo(string.Format(Lng.T("Verschieben nach „{0}“"), new DirectoryInfo(folder).Name), sourcePath, destination);
                UpdateFilePaths(sourcePath, destination);
                LoadPdf(destination); // die verschobene Datei bleibt angezeigt — nun vom neuen Ort (wie in PDFMover)
                CheckForDuplicate(new FileInfo(destination));
                previousFolder = sourceFolder; // beim nächsten Blättern die Rückkehr in den bisherigen Ordner anbieten
                ShowSplash(Lng.T("Datei verschoben")); // das blitzschnelle Neuladen allein wäre leicht zu übersehen
            }
            settings.AddRecentFolder(folder);
            settings.Save();
            UpdateOneClickLabel(); // der zuletzt verwendete Ordner kann jetzt der 1-Klick-Ordner sein
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            TaskDlg.ErrTaskDlg(Handle, copy ? Lng.T("Kopieren fehlgeschlagen.") : Lng.T("Verschieben fehlgeschlagen."), ex);
        }
    }

