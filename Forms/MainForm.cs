                if (error != null)
                {
                    TaskDlg.MsgTaskDlg(Handle, Lng.T("Die E-Mail konnte nicht erstellt werden."), error, TaskDialogIcon.Warning);
                }
            }
        }
        finally
        {
            emailInProgress = false;
            if (currentFile != null) { statusPath.Text = currentFile.FullName; }
        }
    }

