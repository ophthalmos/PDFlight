    // Formulareingaben ändern das Dokument im Hilfsprogramm. In die Datei kommen sie wie jede andere Änderung: still vor der nächsten
    // Programmfunktion (RunAfterCommit, Wunsch vom 26.09.2026), beim Schließen nach Rückfrage. Ebenso die Bearbeitungen über die
    // Viewer-Leiste (Anmerkungen, Drehen) – s. „Bearbeitungen in der Anzeige“ unten.
    // Gespeichert wird eine vollständige Kopie aus PDFium – mit Rückgängig-Sicherung und Schreibschutzprüfung wie jede Bearbeitung.

    // ------------------------------------------------------------------ Bearbeitungen in der Anzeige (Anmerkungen)

    // Anmerkungen (Hervorheben, Zeichnen, Freitext, Stempel, Verschieben, Bearbeiten per Doppelklick) ändern nur das angezeigte Dokument,
    // wie Formulareingaben: „*“ im Titel, „Speichern“ in der Viewer-Leiste, still gespeichert vor jeder anderen Programmfunktion, Rückfrage
    // beim Schließen (Wunsch vom 03.10.2026). Hervorheben und Zeichnen ändern das Dokument im Hilfsprogramm; PDFsharp-Bearbeitungen laufen
    // auf einer Temp-Kopie des angezeigten Stands, der danach aus dem Speicher angezeigt wird (die Datei bleibt bis zum Speichern unberührt).
    // Vor jedem Schritt merkt viewUndo den Stand – Strg+Z nimmt die ungespeicherten Schritte einzeln zurück.

    private sealed record ViewUndo(byte[] Bytes, bool WasDirty, string Description, bool KeepPage = false); // KeepPage: nach dem Drehen nur die Seite halten
    private readonly List<ViewUndo> viewUndo = [];
    private const int ViewUndoLimit = 20;                       // so viele Stände höchstens im Speicher (je ein vollständiges PDF) …
    private const long ViewUndoBytesLimit = 256L * 1024 * 1024; // … und zusammen höchstens so groß – ein 80-MB-Handbuch hätte sonst 1,6 GB belegt (Review 04.10.2026)

    private void AddViewUndo(ViewUndo entry)
    {
        viewUndo.Add(entry);
        // die ältesten fallen weg; der jüngste Stand bleibt immer, auch wenn er allein schon über der Grenze liegt
        while (viewUndo.Count > ViewUndoLimit || (viewUndo.Count > 1 && viewUndo.Sum(u => (long)u.Bytes.Length) > ViewUndoBytesLimit)) { viewUndo.RemoveAt(0); }
        UpdateUndoMenu();
    }

    /// <summary>Den angezeigten Stand vor einem Schritt im Hilfsprogramm merken (Hervorheben, Hervorhebung entfernen).</summary>
    private async Task<bool> PushViewUndoAsync(string description)
    {
        if (ShownDocument is not { } doc) { return false; }
        byte[] bytes;
        try { bytes = await doc.SaveAsync(); }
        catch (InvalidOperationException ex)
        {
            TaskDlg.ErrTaskDlg(Handle, string.Format(Lng.T("{0} fehlgeschlagen."), description), ex);
            return false;
        }
        if (doc != document) { return false; }
        AddViewUndo(new ViewUndo(bytes, documentDirty, description));
        return true;
    }

    /// <summary>Der angezeigte Stand als Datei zum Lesen mit PDFsharp: ohne ungespeicherte Änderungen die Datei selbst, sonst eine
    /// Temp-Kopie (der Aufrufer löscht sie über <see cref="DeleteViewCopy"/>); null bei Fehler.</summary>
    private async Task<string?> ViewStateFileAsync()
    {
        if (currentFile == null) { return null; }
        if (!documentDirty || ShownDocument is not { } doc) { return currentFile.FullName; }
        try
        {
            var bytes = await doc.SaveAsync();
            var temp = NewViewCopyPath();
            await File.WriteAllBytesAsync(temp, bytes);
            return temp;
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or UnauthorizedAccessException) { return null; }
    }

    private static string NewViewCopyPath()
    {
        var folder = Path.Combine(Path.GetTempPath(), "PDFlight");
        Directory.CreateDirectory(folder);
        return Path.Combine(folder, "view-" + Guid.NewGuid().ToString("N") + ".pdf");
    }

    private void DeleteViewCopy(string? path)
    {
        if (path == null || string.Equals(path, currentFile?.FullName, StringComparison.OrdinalIgnoreCase)) { return; } // nie die Datei selbst
        try { File.Delete(path); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { }
    }

    /// <summary>PDFsharp-Bearbeitung am angezeigten Stand: Temp-Kopie bearbeiten, das Ergebnis anzeigen (Ausschnitt bleibt), Stand davor
    /// für Rückgängig merken. Die Datei bleibt bis zum Speichern unberührt.</summary>
    private async Task<bool> EditInViewAsync(Action<string> edit, string actionName, bool keepPage = false)
    {
        if (ShownDocument is not { } doc || currentFile == null) { return false; }
        byte[] before, after;
        string? temp = null;
        try
        {
            before = await doc.SaveAsync();
            if (doc != document) { return false; }
            temp = NewViewCopyPath();
            File.WriteAllBytes(temp, before);
            edit(temp);
            after = File.ReadAllBytes(temp);
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or UnauthorizedAccessException || PdfEditService.IsPdfReadError(ex))
        {
            TaskDlg.ErrTaskDlg(Handle, string.Format(Lng.T("{0} fehlgeschlagen."), actionName), ex);
            return false;
        }
        finally { DeleteViewCopy(temp); }
        var wasDirty = documentDirty;
        if (!await ShowBytesAsync(after, dirty: true, keepPage)) { return false; }
        AddViewUndo(new ViewUndo(before, wasDirty, actionName, keepPage));
        return true;
    }

    /// <summary>Einen Stand aus dem Speicher anzeigen – dieselbe Datei und Anpassung, dazu der Ausschnitt (keepPage: nur die angezeigte
    /// Seite – nach dem Drehen passt der alte Bildlauf nicht mehr).</summary>
    private async Task<bool> ShowBytesAsync(byte[] bytes, bool dirty, bool keepPage = false)
    {
        if (currentFile == null || document == null) { return false; }
        var path = currentFile.FullName;
        var view = new ViewState(pageView.Fit, pageView.Zoom, keepPage ? null : pageView.ScrollOffset);
        documentLoading = OpenDocumentAsync(path, bytes, pageView.CurrentPage + 1, view);
        if (await documentLoading == null || currentFile?.FullName != path) { return false; }
        documentDirty = dirty;
        UpdateTitle();
        return true;
    }

    /// <summary>Strg+Z bei ungespeicherten Schritten: den Stand vor dem letzten anzeigen.</summary>
    private async void UndoViewChange()
    {
        if (viewUndo.Count == 0) { return; }
        var entry = viewUndo[^1];
        viewUndo.RemoveAt(viewUndo.Count - 1);
        UpdateUndoMenu();
        if (await ShowBytesAsync(entry.Bytes, entry.WasDirty, entry.KeepPage)) { statusPath.Text = Lng.T("Rückgängig:") + " " + entry.Description; }
    }

