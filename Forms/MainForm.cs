    private async void MainForm_Shown(object? sender, EventArgs e)
    {
        try { await viewHost.InitializeAsync(); }
        catch (WebView2RuntimeNotFoundException)
        {
            TaskDlg.MsgTaskDlg(Handle, Lng.T("Die WebView2-Runtime ist nicht installiert."), Lng.T("Bitte installiere sie über:") + Environment.NewLine + "https://developer.microsoft.com/microsoft-edge/webview2/", TaskDialogIcon.Error);
            Close();
            return;
        }
        catch (Exception ex) when (ex is DllNotFoundException or InvalidOperationException or System.Runtime.InteropServices.COMException or IOException or UnauthorizedAccessException)
        {
            // z.B. beschädigte Installation oder gesperrter Datenordner — sauberer Dialog statt WinForms-Absturzfenster
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Die PDF-Anzeige (WebView2) konnte nicht gestartet werden."), ex);
            Close();
            return;
        }
        webView.KeyDown += WebView_KeyDown; // Tastenkürzel funktionieren auch, wenn der Viewer den Fokus hat
        viewHost.ZoomChanged += ViewHost_ZoomChanged;
        viewHost.PdfFileDropped += (s, path) => OpenDroppedFiles([path]); // Drop auf das Viewer-Areal
        InitDropDownClickShield();
        EnableClassicDragDrop();
        ShellUtil.RegisterFileType(); // Datei-Icon und Öffnen-Befehl je Benutzer, unabhängig vom Installer-Task

        if (options.Help) { ShowHelpFile(); } // nach der Installation: die Hilfedatei als erstes Dokument
        else if (!string.IsNullOrEmpty(options.File) && File.Exists(options.File))
        {
            LoadPdf(options.File, options.Page, addToRecent: true);
            if (options.Print) { await PrintAndCloseAsync(); }
        }
        else if (settings.ReopenLastFile && !string.IsNullOrEmpty(settings.LastFile) && File.Exists(settings.LastFile)) { LoadPdf(settings.LastFile); }
        else { UpdateUiState(); }
    }

    /// <summary>Start mit /print: das Dokument ohne Dialog auf dem Standarddrucker (bzw. /print:Druckername) ausgeben
    /// und PDFlight beenden – so bedient PDFlight auch das Explorer-Kontextmenü „Drucken“.</summary>
    private async Task PrintAndCloseAsync()
    {
        statusPath.Text = Lng.T("Drucke …");
        var status = await viewHost.PrintAsync(options.Printer);
        if (status != CoreWebView2PrintStatus.Succeeded)
        {
            var reason = status == CoreWebView2PrintStatus.PrinterUnavailable ? Lng.T("Der Drucker ist nicht verfügbar.") : Lng.T("Das Dokument konnte nicht gedruckt werden.");
            TaskDlg.MsgTaskDlg(Handle, Lng.T("Drucken fehlgeschlagen."), reason + (string.IsNullOrEmpty(options.Printer) ? string.Empty : "\n" + options.Printer), TaskDialogIcon.Error);
        }
        Close();
    }

    /// <summary>Erzeugt die Hilfedatei neu (Downloads-Ordner, aktuelle Programmsprache) und zeigt sie an – Start mit /help.</summary>
    private void ShowHelpFile()
    {
        try { LoadPdf(ShortcutsPdf.Create()); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Die Hilfedatei konnte nicht erstellt werden."), ex);
            UpdateUiState();
        }
    }

    private void MainForm_FormClosing(object? sender, FormClosingEventArgs e)
    {
        try { File.Delete(OwnUndoBackup); } // die eigene Undo-Sicherung wird beim Beenden entsorgt
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException) { } // sonst räumt sie der nächste Start ab
        InstanceRegistry.Clear(); // diese Instanz zeigt nichts mehr an
        viewHost.ReleaseZoomHook();
        SetFullScreen(false); // sonst würden randlose Vollbild-Maße gespeichert
        settings.ReloadSharedLists(); // Listenänderungen anderer Instanzen nicht überschreiben
        settings.LastFile = currentFile?.FullName ?? string.Empty;
        var bounds = WindowState == FormWindowState.Normal ? Bounds : RestoreBounds;
        settings.WindowX = bounds.X;
        settings.WindowY = bounds.Y;
        settings.WindowWidth = bounds.Width;
        settings.WindowHeight = bounds.Height;
        if (!options.Maximized) { settings.WindowMaximized = WindowState == FormWindowState.Maximized; } // /max ist einmalig, nicht die gemerkte Vorgabe
        settings.Save();
    }

    private void MainForm_Activated(object? sender, EventArgs e)
    {
        if (currentFile == null) { return; }
        try
        {
            // Datei wurde extern verschoben, umbenannt oder gelöscht → fragen, wie es weitergehen soll
            if (!File.Exists(currentFile.FullName)) { HandleMissingFile(); return; }
            // Datei wurde extern geändert (z.B. in einem anderen Programm gespeichert) → Anzeige aktualisieren
            if (File.GetLastWriteTimeUtc(currentFile.FullName) != loadedWriteTimeUtc)
            {
                LoadPdf(currentFile.FullName);
            }
        }
        catch (IOException) { }
    }

    /// <summary>Die angezeigte Datei ist von der Platte verschwunden. Die Anzeige stammt aus dem
    /// Speicher und funktioniert weiter — der Dialog bietet an, die Datei daraus am alten Ort neu zu
    /// speichern (für weitere Bearbeitung) oder sie nur noch anzuzeigen (Datei- und
    /// Bearbeitungsfunktionen deaktiviert, bis eine andere Datei geöffnet wird).</summary>
    private void HandleMissingFile()
    {
        if (missingFileNoticeShown || currentFile == null) { return; }
        missingFileNoticeShown = true; // vor dem Dialog setzen — sein Schließen aktiviert das Formular erneut
        TaskDialogButton btnResave = new TaskDialogCommandLinkButton(Lng.T("Datei neu speichern"),
            Lng.T("Stellt die Datei am alten Ort wieder her"));
        TaskDialogButton btnViewOnly = new TaskDialogCommandLinkButton(Lng.T("Nur weiter anzeigen"),
            Lng.T("Bearbeitungsfunktionen werden deaktiviert"));
        var page = new TaskDialogPage()
        {
            Icon = TaskDialogIcon.ShieldWarningYellowBar,
            Caption = Application.ProductName,
            Heading = Lng.T("Die angezeigte Datei existiert nicht mehr!"),
            Text = currentFile.FullName + "\n\n" + Lng.T("FehlendeDatei.Text", // mehrzeilig → expliziter Schlüssel (wie Drehen.Info)
                "Sie wurde extern verschoben, umbenannt oder gelöscht.\nDie Anzeige stammt aus dem Speicher und bleibt erhalten."),
            AllowCancel = true,
            SizeToContent = true,
            Buttons = { btnResave, btnViewOnly },
            DefaultButton = btnResave
        };
        if (TaskDialog.ShowDialog(Handle, page) == btnResave && viewHost.DocumentBytes is { } bytes)
        {
            try
            {
                File.WriteAllBytes(currentFile.FullName, bytes);
                LoadPdf(currentFile.FullName); // frischer Zustand — alle Funktionen stehen wieder bereit
                statusPath.Text = Lng.T("Die Datei wurde aus der Anzeige neu gespeichert.");
                return;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or DirectoryNotFoundException)
            {
                TaskDlg.ErrTaskDlg(Handle, Lng.T("Die Datei konnte nicht gespeichert werden."), ex);
            }
        }
        // Nur anzeigen (auch bei Abbruch oder fehlgeschlagenem Speichern): Dateibezug lösen —
        // alle Datei- und Bearbeitungsfunktionen deaktivieren sich darüber, die Anzeige bleibt bestehen
        var name = currentFile.Name;
        currentFile = null;
        UpdateUiState();
        Text = name + " – PDFlight";
        statusPath.Text = name + " – " + Lng.T("Die Datei wurde verschoben oder gelöscht; die Anzeige stammt aus dem Speicher.");
    }

    private void RestoreWindowBounds()
    {
        if (settings.WindowWidth > 200 && settings.WindowHeight > 200)
        {
            Rectangle bounds = new(settings.WindowX, settings.WindowY, settings.WindowWidth, settings.WindowHeight);
            if (Screen.AllScreens.Any(s => s.WorkingArea.IntersectsWith(bounds))) // nicht auf einem abgesteckten Monitor wiederherstellen
            {
                StartPosition = FormStartPosition.Manual;
                Bounds = bounds;
            }
        }
        if (settings.WindowMaximized || options.Maximized) { WindowState = FormWindowState.Maximized; } // /max erzwingt es
    }

