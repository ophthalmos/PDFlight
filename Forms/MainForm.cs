    /// <summary>Kürzel, die die Datei nicht berühren – sie laufen ohne vorheriges Speichern offener Formulareingaben: Hilfe, Vollbild, Esc
    /// (Beenden fragt selbst nach), Einstellungen (auch die Datei), Pfad kopieren, Favorit, Windows-Dateieigenschaften und die Ansicht.</summary>
    private static bool IsViewNeutral(Keys keyData) => keyData is Keys.F1 or Keys.F3 or (Keys.F3 | Keys.Shift) or Keys.F11 or Keys.Escape or (Keys.Escape | Keys.Shift)
        or (Keys.Oemcomma | Keys.Control) or (Keys.F2 | Keys.Control | Keys.Shift) or (Keys.C | Keys.Control | Keys.Shift)
        or (Keys.D | Keys.Control) or (Keys.Enter | Keys.Alt) or (Keys.F | Keys.Control) or (Keys.G | Keys.Control)
        or (Keys.I | Keys.Control | Keys.Shift) or (Keys.B | Keys.Control | Keys.Shift) or (Keys.R | Keys.Control | Keys.Shift) or (Keys.L | Keys.Control | Keys.Shift)
        or (Keys.Add | Keys.Control) or (Keys.Oemplus | Keys.Control) or (Keys.Subtract | Keys.Control) or (Keys.OemMinus | Keys.Control)
        or (Keys.D0 | Keys.Control) or (Keys.NumPad0 | Keys.Control) or (Keys.Space | Keys.Control) or (Keys.S | Keys.Control);

    /// <summary>Kürzel, die selbst in der Anzeige bearbeiten (Anmerkungen) oder deren Schritte zurücknehmen – davor wird nicht gespeichert.</summary>
    private bool IsViewEdit(Keys keyData) => keyData is (Keys.T | Keys.Control) or (Keys.H | Keys.Control)
        || (keyData == (Keys.Z | Keys.Control) && viewUndo.Count > 0);

    /// <summary>Die Aktion zu einem Tastenkürzel – null, wenn die Taste keins ist (dann läuft sie an das Steuerelement mit dem Fokus weiter).</summary>
    private Action? ResolveShortcut(Keys keyData)
    {
        switch (keyData)
        {
            case Keys.O | Keys.Control: return OpenFile;
            case Keys.F4:
            case Keys.M | Keys.Control: return () => MoveCopyDialog(copy: false);
            case Keys.K | Keys.Control: return () => MoveCopyDialog(copy: true);
            case Keys.M | Keys.Control | Keys.Shift:
            case Keys.F4 | Keys.Control: return () => { if (!OneClickAction(copy: false)) { MoveCopyDialog(copy: false); } };
            case Keys.K | Keys.Control | Keys.Shift: return () => { if (!OneClickAction(copy: true)) { MoveCopyDialog(copy: true); } };
            case Keys.F2:
            case Keys.U | Keys.Control: return RenameCurrent;
            case Keys.Delete | Keys.Control when !EditLocked: return DeletePagesDialog;
            case Keys.Insert | Keys.Control when !EditLocked: return InsertPageDialog;     // Gegenstück zu Strg+Entf
            case Keys.X | Keys.Control: return ExtractPagesDialog;                         // eXtrahieren
            case Keys.Y | Keys.Control when mnuMovePage.Enabled: return MovePageDialog;    // aktuelle Seite verschieben
            case Keys.N | Keys.Control when !EditLocked: return AppendPdfDialog;           // PDF-Datei anhängen
            case Keys.T | Keys.Control when !EditLocked: return AddAnnotationDialog;       // Textanmerkung
            case Keys.H | Keys.Control when !EditLocked: return AddStampDialog;            // Stempel
            case Keys.H | Keys.Control | Keys.Shift: return ManageStampsDialog;            // Stempelpalette pflegen
            case Keys.T | Keys.Control | Keys.Shift when mnuManageAnnotations.Enabled: return ManageAnnotationsDialog;
            case Keys.Delete | Keys.Control | Keys.Shift when currentFile != null: return DeleteCurrent;
            case Keys.R | Keys.Control when !EditLocked: return RotatePagesDialog;
            case Keys.P | Keys.Control when currentFile != null: return PrintWithDialog;
            case Keys.W | Keys.Control when currentFile != null || document != null: return CloseDocument; // wie ein Tab im Browser
            case Keys.S | Keys.Control when documentDirty: return SaveFormInput;           // Formulareingaben speichern
            case Keys.P | Keys.Control | Keys.Shift when currentFile != null: return PrintWithSystemDialog; // wie in Edge
            // Ansicht
            case Keys.R | Keys.Control | Keys.Shift when !EditLocked: return () => RotateAllPages(clockwise: true); // alle Seiten, ungespeichert
            case Keys.L | Keys.Control | Keys.Shift when !EditLocked: return () => RotateAllPages(clockwise: false);
            case Keys.G | Keys.Control: return FocusPageBox;                               // Gehe zu Seite (Zahl + Enter)
            case Keys.I | Keys.Control | Keys.Shift: return ToggleSidebar;                 // Seitenleiste
            case Keys.B | Keys.Control | Keys.Shift: return ToggleFit;                     // an Breite / an Seite anpassen
            case Keys.Space | Keys.Control: return ToggleTwoPage;                         // ein-/zweiseitig
            case Keys.F | Keys.Control: return ShowSearch;
            case Keys.F3: return () => pageView.NextHit(backwards: false);
            case Keys.F3 | Keys.Shift: return () => pageView.NextHit(backwards: true);
            case Keys.Add | Keys.Control:
            case Keys.Oemplus | Keys.Control: return pageView.ZoomIn;                      // auch mit dem Fokus in der Seitenleiste
            case Keys.Subtract | Keys.Control:
            case Keys.OemMinus | Keys.Control: return pageView.ZoomOut;
            case Keys.D0 | Keys.Control:
            case Keys.NumPad0 | Keys.Control: return () => pageView.SetZoom(1f, null);
            // Datei und Programm
            case Keys.Z | Keys.Control when viewUndo.Count > 0: return UndoViewChange;     // ungespeicherte Schritte in der Anzeige
            case Keys.Z | Keys.Control when undoAction != null: return UndoLastChange;
            case Keys.I | Keys.Control: return ShowProperties;
            case Keys.Oemcomma | Keys.Control: return () => OpenSettings(SettingsForm.TabGeneral); // Strg+, wie in vielen Editoren
            case Keys.Enter | Keys.Alt when currentFile != null: return () => { if (currentFile != null) { ShellUtil.ShowFileProperties(currentFile.FullName); } }; // Windows-Dateieigenschaften, wie im Explorer
            case Keys.C | Keys.Control | Keys.Shift when currentFile != null: return CopyPathToClipboard; // wie im Windows-11-Explorer
            case Keys.E | Keys.Control: return EmailCurrent;
            case Keys.D | Keys.Control when settings.ShowFavorites: return ToggleFavorite; // Datei als Favorit merken / wieder austragen
            case Keys.Right | Keys.Control | Keys.Shift: return () => StepFile(1);
            case Keys.Left | Keys.Control | Keys.Shift: return () => StepFile(-1);
            case Keys.F1: return ShowHelp;
            case Keys.F2 | Keys.Control when mnuEditBookmarks.Enabled: return EditBookmarks; // Lesezeichen-Editor; bewusst nicht in der Kürzeltabelle (Platz)
            case Keys.F2 | Keys.Control | Keys.Shift: return OpenSettingsFile;             // settings.json im Editor – bewusst undokumentiert (Wunsch vom 20.09.2026)
            case Keys.F11: return () => SetFullScreen(!isFullScreen);
            case Keys.Escape when pageView.IsPicking: return pageView.CancelPick;           // Stelle wählen abbrechen
            case Keys.Escape when pageView.IsMovingAnnotation: return pageView.ClearAnnotationGhost; // Verschieben abbrechen
            case Keys.Escape when highlightMode || pageView.InkMode: return EndAnnotationModes;     // Hervorheben-/Zeichenmodus beenden
            case Keys.Escape | Keys.Shift when settings.CloseOnEscape: return Close;      // Shift+Esc beendet sofort (wie in NetRadio)
            case Keys.Escape when escHoldTimer.Enabled: return () => { };              // Tastenwiederholung nach dem Beenden des Vollbilds
            case Keys.Escape when SearchOpen: return CloseSearch;                        // zuerst die Suche
            case Keys.Escape when isFullScreen: return ExitFullScreenByEscape;
            case Keys.Escape when settings.CloseOnEscape: return ResolveEscapeToClose();
        }
        if ((keyData & (Keys.Control | Keys.Alt | Keys.Shift)) == Keys.Control)
        {
            var key = keyData & Keys.KeyCode;
            if (key is >= Keys.D1 and <= Keys.D9) { return () => LaunchProgramByIndex(key - Keys.D1); }             // Strg+1 … Strg+9: externe Programme
            if (key is >= Keys.NumPad1 and <= Keys.NumPad9) { return () => LaunchProgramByIndex(key - Keys.NumPad1); } // dasselbe über den Ziffernblock
        }
        return null;
    }

    /// <summary>Kopiert den vollständigen Pfad der angezeigten Datei in die Zwischenablage (Strg+Umschalt+C, wie im Explorer).</summary>
    private void CopyPathToClipboard()
    {
        if (currentFile == null) { return; }
        try
        {
            Clipboard.SetText(currentFile.FullName);
            statusPath.Text = Lng.T("Der Dateipfad wurde in die Zwischenablage kopiert.");
        }
        catch (System.Runtime.InteropServices.ExternalException ex) // Zwischenablage von anderem Programm gesperrt
        {
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Kopieren in die Zwischenablage fehlgeschlagen."), ex);
        }
    }

    private DateTime lastEscape = DateTime.MinValue;

    /// <summary>Beenden erst beim zweiten Esc kurz hintereinander: Das erste Esc wird nicht verschluckt – es hebt in der Anzeige die
    /// Markierung auf bzw. beendet die Eingabe in einem Formularfeld. Shift+Esc beendet sofort (s. ResolveShortcut).</summary>
    private Action? ResolveEscapeToClose()
    {
        var now = DateTime.UtcNow;
        if ((now - lastEscape).TotalMilliseconds <= 1500) { return Close; }
        lastEscape = now;
        return null; // das erste Esc geht an die Anzeige
    }


    protected override bool ProcessCmdKey(ref Message msg, Keys keyData)
    {
        if (TextInputFocused && IsTextEditingKey(keyData)) { return base.ProcessCmdKey(ref msg, keyData); } // das Textfeld braucht die Taste selbst
        if (ResolveShortcut(keyData) is { } action)
        {
            if (documentDirty && !IsViewNeutral(keyData) && !IsViewEdit(keyData)) { RunAfterCommit(action); } // offene Änderungen zuerst in die Datei
            else { action(); }
            return true;
        }
        return base.ProcessCmdKey(ref msg, keyData);
    }

    /// <summary>Getippt wird gerade in ein Textfeld: Seitenfeld, Zoomfeld, Suchfeld oder ein Formularfeld der angezeigten Seite.</summary>
    private bool TextInputFocused => textPage.Focused || textSearch.Focused || comboZoom.Focused || (pageView.Focused && pageView.FormFocused);

    /// <summary>Tasten, die ein Textfeld selbst braucht (Bearbeiten, Markieren, Zwischenablage, Esc) – dort haben sie Vorrang vor den
    /// Kürzeln. Strg+Umschalt+Entf (Datei löschen) bleibt ein Kürzel.</summary>
    private static bool IsTextEditingKey(Keys keyData)
    {
        var key = keyData & Keys.KeyCode;
        if (key is Keys.Escape or Keys.Delete or Keys.Back or Keys.Home or Keys.End or Keys.Left or Keys.Right or Keys.Up or Keys.Down or Keys.Insert)
        {
            return keyData != (Keys.Delete | Keys.Control | Keys.Shift);
        }
        return (keyData & Keys.Modifiers) == Keys.Control && key is Keys.A or Keys.C or Keys.V or Keys.X or Keys.Z or Keys.Y;
    }

