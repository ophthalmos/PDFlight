    /// <summary>Zeigt eine Datei an. Datei- und Statusangaben (Titel, Statusleiste, Sperren) stehen sofort; das Dokument selbst öffnet
    /// das Hilfsprogramm im Hintergrund (<see cref="OpenDocumentAsync"/>) – bis dahin bleibt die bisherige Anzeige stehen, und Seitenzahl,
    /// Version, Verschlüsselung und Lesezeichen sind noch unbekannt (Seitenzahl -1, Bearbeitung gesperrt). Ohne Seitenangabe öffnet es auf
    /// der gemerkten Seite (Option), sonst auf Seite 1. Bei derselben Datei (Neuladen nach einer Bearbeitung) bleiben Anpassung bzw.
    /// Zoomstufe und, wenn die Zielseite schon zu sehen ist, auch der Ausschnitt erhalten.</summary>
    private void LoadPdf(string path, int page = 0, bool addToRecent = false)
    {
        if (addToRecent) { previousFolder = null; } // bewusstes Öffnen beendet den Verschieben-Kontext fürs Blättern
        viewUndo.Clear(); // ungespeicherte Schritte der Anzeige gehören zum bisherigen Stand
        UpdateUndoMenu();
        if (RememberCurrentPage()) { settings.Save(); } // die Seite der bisherigen Datei merken, bevor sie ersetzt wird
        byte[] bytes;
        try { bytes = File.ReadAllBytes(path); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Die Datei konnte nicht geladen werden."), ex);
            return;
        }
        // PDF/A per Textsuche; Seitenzahl, Version, Verschlüsselung und Lesezeichen liefert das Hilfsprogramm nach dem Laden (OpenDocumentAsync)
        var status = new PdfStatus(-1, null, PdfStatus.DetectPdfALevel(bytes));
        var targetPage = page > 0 ? page : settings.RememberLastPage && settings.GetLastPage(path) is > 1 and var remembered ? remembered : 0;
        var sameFile = currentFile != null && document != null && string.Equals(currentFile.FullName, path, StringComparison.OrdinalIgnoreCase);
        // Anzeige wie zuletzt: dieselbe Datei auch mit ihrer Drehung, eine andere mit Anpassung bzw. Zoomstufe der bisherigen, die erste
        // nach dem Start mit den beim Beenden gemerkten Einstellungen
        var keepScroll = sameFile && (page <= 0 || pageView.IsPageVisible(page - 1)); // nach einer Bearbeitung bleibt der Ausschnitt, wenn die Zielseite schon zu sehen ist
        var view = document != null ? new ViewState(pageView.Fit, pageView.Zoom, keepScroll ? pageView.ScrollOffset : null) : startView;
        currentFile = new FileInfo(path);
        loadedWriteTimeUtc = currentFile.LastWriteTimeUtc;
        currentPdfStatus = status;
        currentPageCount = currentPdfStatus.PageCount;
        pdfAEditingEnabled = false; // jede geladene PDF/A-Datei startet wieder schreibgeschützt
        missingFileNoticeShown = false;
        if (addToRecent) // nur bei bewusstem Öffnen — nicht beim Blättern durch den Ordner
        {
            settings.ReloadSharedLists();
            settings.AddRecentFile(currentFile.FullName);
            settings.Save();
        }
        documentLoading = OpenDocumentAsync(path, bytes, targetPage, view, newFile: !sameFile);
        UpdateUiState();
    }

    /// <summary>Anpassung bzw. feste Zoomstufe – beim Laden der nächsten Datei übernommen – und bei derselben Datei der Ausschnitt
    /// (Bildlauf). Eine Drehung der Ansicht gibt es seit 03.10.2026 nicht mehr: die Viewer-Leiste dreht die Seiten selbst.</summary>
    private sealed record ViewState(PageFit Fit, float Zoom, Point? Scroll = null);

    /// <summary>Anzeige für die erste Datei nach dem Start: wie beim letzten Beenden (s. MainForm_FormClosing).</summary>
    private ViewState? startView;

    private Task<PdfiumDocument?> documentLoading = Task.FromResult<PdfiumDocument?>(null);

    /// <summary>Das Dokument, sobald das laufende Laden fertig ist (null, wenn es scheiterte oder überholt wurde).</summary>
    private Task<PdfiumDocument?> WaitForDocumentAsync() => documentLoading;

    /// <summary>Öffnet die Datei im Hilfsprogramm und zeigt sie an – mit Kennwortabfrage, wenn die Datei ein Benutzer-Kennwort hat (das
    /// Kennwort merkt sich PDFlight bis zum Beenden, damit das Neuladen nach einer Bearbeitung nicht erneut fragt).</summary>
    private async Task<PdfiumDocument?> OpenDocumentAsync(string path, byte[] bytes, int page, ViewState? view, bool newFile = false)
    {
        var version = ++loadVersion;
        passwords.TryGetValue(path, out var password);
        PdfiumDocument opened;
        while (true)
        {
            try
            {
                opened = await PdfiumDocument.OpenAsync(bytes, path, password);
                break;
            }
            catch (PasswordRequiredException ex)
            {
                if (version != loadVersion || IsDisposed) { return null; }
                if (ex.WrongPassword) { TaskDlg.MsgTaskDlg(Handle, Lng.T("Das Kennwort ist falsch."), null, TaskDialogIcon.Warning); }
                using PasswordForm dialog = new(Path.GetFileName(path), title: Lng.T("Geschützte Datei öffnen"));
                if (dialog.ShowDialog(this) != DialogResult.OK || version != loadVersion)
                {
                    if (version == loadVersion) { ShowDocument(null); statusPath.Text = Lng.T("Ohne Kennwort lässt sich die Datei nicht anzeigen."); }
                    return null;
                }
                password = dialog.Password;
            }
            catch (InvalidOperationException ex)
            {
                if (version != loadVersion || IsDisposed) { return null; }
                ShowDocument(null);
                TaskDlg.ErrTaskDlg(Handle, Lng.T("Die Datei konnte nicht angezeigt werden."), ex);
                return null;
            }
        }
        if (version != loadVersion || IsDisposed) { opened.Dispose(); return null; }
        if (password != null) { passwords[path] = password; }
        ShowDocument(opened);
        if (view != null) { if (view.Fit == PageFit.None) { pageView.SetZoom(view.Zoom, null); } else { pageView.SetFit(view.Fit); } }
        if (view?.Scroll is { } scroll) { pageView.ScrollOffset = scroll; }
        else if (page > 1) { pageView.GoToPage(page - 1); }
        var (fileVersion, encrypted) = await opened.InfoAsync();
        var outline = await opened.OutlineAsync();
        if (opened == document)
        {
            FillOutline(outline);
            // Status aus dem Hilfsprogramm (früher las PDFsharp die Datei dafür ungeschützt im Hauptprozess) – nur nach LoadPdf (Seitenzahl
            // noch -1); ein Stand aus dem Speicher (ShowBytesAsync: Anmerkungen, Drehen, Rückgängig) ändert weder Seitenzahl noch
            // Verschlüsselung noch Lesezeichen, und UpdateUiState läse sonst bei jedem Schritt den ganzen Ordner neu (Review 04.10.2026)
            if (currentPageCount < 0)
            {
                static int Count(IEnumerable<OutlineItem> items) => items.Sum(i => 1 + Count(i.Children));
                currentPdfStatus = (currentPdfStatus ?? new PdfStatus(-1, null, null)) with { PageCount = opened.PageCount, Version = fileVersion, Encrypted = encrypted, OutlineCount = Count(outline) };
                currentPageCount = opened.PageCount;
                var message = statusPath.Text;
                UpdateUiState();
                statusPath.Text = message; // die Meldung des Aufrufers („Die Seiten wurden gelöscht.“ …) bleibt – UpdateUiState setzte den Pfad
            }
            if (newFile) { ApplySidebarForDocument(hasOutline: outline.Count > 0); } // nicht beim Neuladen derselben Datei
        }
        return opened;
    }

    /// <summary>Wechselt das angezeigte Dokument (null = keins) in allen Ansichten; das bisherige wird danach im Hilfsprogramm geschlossen.</summary>
    private void ShowDocument(PdfiumDocument? value)
    {
        if (document != null && value == null) { startView = new ViewState(pageView.Fit, pageView.Zoom); } // die nächste Datei wieder so anzeigen
        var previous = document;
        previous?.Changed -= Document_Changed;
        document = value;
        document?.Changed += Document_Changed;
        documentDirty = false;
