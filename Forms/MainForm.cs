        settings.AnnotationBackground = style.BackgroundHex;
        settings.AnnotationTextColor = style.TextColorHex;
        settings.Save();
        var (text, left, top, size) = (dialog.AnnotationText, dialog.LeftMm, dialog.TopMm, dialog.FontSize);
        if (await EditInViewAsync(path => PdfEditService.AddFreeTextAnnotation(path, page, text, left, top, size, style), Lng.T("Textanmerkung")))
        {
            statusPath.Text = string.Format(Lng.T("Die Textanmerkung wurde auf Seite {0} eingefügt."), page);
        }
    }

