    private void LayoutViewerStrip()
    {
        static int Width(ToolStripItem item) => item.Available ? item.GetPreferredSize(Size.Empty).Width + item.Margin.Horizontal : 0;
        ToolStripItem[] center = [textPage, labelPageCount, toolStripSeparatorV2, btnZoomOut, comboZoom, btnZoomIn, btnFitWidth, btnTwoPage, toolStripSeparatorV3, btnRotateLeft, btnRotateRight];
        var centerWidth = center.Sum(Width);
        var rightWidth = viewerStrip.Items.Cast<ToolStripItem>().Where(i => i.Alignment == ToolStripItemAlignment.Right).Sum(Width);
        var available = viewerStrip.DisplayRectangle.Width;
        // Beschriftung der Anmerkungs-Schaltflächen wie in der Symbolleiste („ohne Text“ dort = auch hier ohne) – aber nur, solange links,
        // Mitte und rechts nebeneinander Platz haben; bei schmalem Fenster bleiben die Symbole (Tooltips nennen die Funktion)
        var left = viewerStrip.Items.Cast<ToolStripItem>().TakeWhile(i => i != labelViewerSpacer).ToList();
        int LeftWidth(bool text)
        {
            viewerStrip.SuspendLayout();
            try
            {
                var styles = ViewerTextItems.ToDictionary(i => i, i => i.DisplayStyle);
                foreach (var item in ViewerTextItems) { item.DisplayStyle = TextStyle(item, text); }
                var width = left.Sum(Width);
                foreach (var (item, style) in styles) { item.DisplayStyle = style; }
                return width;
            }
            finally { viewerStrip.ResumeLayout(false); }
        }
        var wantText = settings.ShowToolbarText;
        var shown = ViewerTextItems.Any(i => i.DisplayStyle == ToolStripItemDisplayStyle.ImageAndText);
        var withText = wantText ? LeftWidth(text: true) : 0;
        var margin = LogicalToDeviceUnits(shown ? 8 : 24); // Abstand zum Umschalten, beim Einblenden größer – sonst wechselt es an der Grenze hin und her
        var showText = wantText && withText + centerWidth + rightWidth + labelViewerSpacer.Margin.Horizontal + margin <= available;
        foreach (var item in ViewerTextItems)
        {
            var style = TextStyle(item, showText);
            if (item.DisplayStyle != style) { item.DisplayStyle = style; }
        }
        var leftWidth = left.Sum(Width) + labelViewerSpacer.Margin.Horizontal; // Seitenleiste und Anmerkungen
        var centered = (available - centerWidth) / 2 - leftWidth;
        var spacer = Math.Max(0, Math.Min(centered, available - leftWidth - centerWidth - rightWidth - LogicalToDeviceUnits(8)));
        if (labelViewerSpacer.Width != spacer) { labelViewerSpacer.Width = spacer; }
    }

