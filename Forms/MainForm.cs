    private void LoadPdf(string path, int page = 0, bool addToRecent = false)
    {
        if (addToRecent) { previousFolder = null; } // bewusstes Öffnen beendet den Verschieben-Kontext fürs Blättern
        viewerDialogOpen = false; // das Neuladen des Dokuments schließt auch offene Viewer-Dialoge
        try { viewHost.Load(path, page); }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            TaskDlg.ErrTaskDlg(Handle, Lng.T("Die Datei konnte nicht geladen werden."), ex);
            return;
        }
        currentFile = new FileInfo(path);
        loadedWriteTimeUtc = currentFile.LastWriteTimeUtc;
        currentPdfStatus = PdfEditService.TryReadStatus(path);
        currentPageCount = currentPdfStatus.PageCount;
        viewHost.SetPageSize(currentPdfStatus.PageWidthPt, currentPdfStatus.PageHeightPt); // Referenz für die Zoomanzeige
        statusZoom.Visible = false; // bis der Viewer die Zoomstufe des neuen Dokuments meldet
        pdfAEditingEnabled = false; // jede geladene PDF/A-Datei startet wieder schreibgeschützt
        missingFileNoticeShown = false;
        if (addToRecent) // nur bei bewusstem Öffnen — nicht beim Blättern durch den Ordner
        {
            settings.ReloadSharedLists();
            settings.AddRecentFile(currentFile.FullName);
            settings.Save();
        }
        UpdateUiState();
    }

    private void UpdateUiState()
    {
        var hasFile = currentFile != null;
        InstanceRegistry.Publish(currentFile?.FullName); // den anderen Instanzen melden, welche Datei hier offen ist
        Text = hasFile ? (settings.ShowFullPathInTitle ? currentFile!.FullName : currentFile!.Name) + " – PDFlight" : "PDFlight";
        splitButtonMove.Enabled = btnCopy.Enabled = btnRename.Enabled = btnDelete.Enabled = btnShowInFolder.Enabled = ddbEdit.Enabled = btnPrint.Enabled = btnEmail.Enabled = hasFile;
        // PDF/A-Schutz: verändernde Operationen bleiben gesperrt, bis „Bearbeitung aktivieren“ gedrückt wurde;
        // Extrahieren (neue Datei), Rückgängig (stellt alte Bytes wieder her) und Eigenschaften (dann nur lesend) bleiben frei
        pnlPdfA.Visible = hasFile && PdfALocked;
        mnuDeletePages.Enabled = mnuRotatePages.Enabled = mnuAppendPdf.Enabled = mnuDuplex.Enabled = mnuAddAnnotation.Enabled = !PdfALocked;
        mnuManageAnnotations.Enabled = !PdfALocked && (currentPdfStatus?.AnnotationCount ?? 0) > 0; // ohne Anmerkungen gibt es nichts zu verwalten
        mnuSetPassword.Enabled = currentPageCount > 0 && !PdfALocked;  // nur ohne bestehenden Kennwortschutz
        mnuRemovePassword.Enabled = hasFile && currentPageCount <= 0;  // nur bei geschützter (oder unlesbarer) Datei
        foreach (var button in programIconButtons) { button.Enabled = hasFile; }
        if (hasFile)
        {
            var files = FileUtil.GetPdfFilesInFolder(currentFile!.DirectoryName!);
            var index = files.FindIndex(f => string.Equals(f, currentFile.FullName, StringComparison.OrdinalIgnoreCase));
            statusIndex.Text = Lng.T("Datei") + " " + (index >= 0 ? (index + 1).ToString() : "–") + "/" + files.Count;
            statusPath.Text = currentFile.FullName;
            var pages = currentPageCount > 0 ? currentPageCount + " " + (currentPageCount == 1 ? Lng.T("Seite") : Lng.T("Seiten")) + "   " : string.Empty;
            statusInfo.Text = $"{pages}{currentFile.Length / 1024.0:N0} KB   {currentFile.LastWriteTime:g}";
            UpdateFormatLabel();
            btnPrev.Enabled = btnNext.Enabled = files.Count > 1;
        }
        else
        {
            statusIndex.Text = Lng.T("Datei") + " 0/0";
            statusPath.Text = Lng.T("Keine Datei geöffnet");
            statusInfo.Text = string.Empty;
            statusFormat.Visible = false;
            statusZoom.Visible = false;
            btnPrev.Enabled = btnNext.Enabled = false;
        }
        UpdateOneClickLabel();
    }

    /// <summary>True, solange die angezeigte PDF/A-Datei schreibgeschützt ist (Banner sichtbar).</summary>
    private bool PdfALocked => currentPdfStatus?.PdfALevel != null && !pdfAEditingEnabled;

    /// <summary>„Bearbeitung aktivieren“ im PDF/A-Banner: hebt nach einer Warnung den Schreibschutz
    /// für diese Datei auf. Die Datei selbst bleibt dabei unverändert — die PDF/A-Kennzeichnung geht
    /// erst verloren, wenn tatsächlich eine Bearbeitung ausgeführt und die Datei neu gespeichert wird.</summary>
    private void BtnPdfAEnable_Click(object? sender, EventArgs e)
    {
        if (!TaskDlg.ConfirmTaskDlg(Handle,
            Lng.T("Möchtest du den Vorgang fortsetzen?"),
            Lng.T("Das Bearbeiten führt dazu, dass die PDF-Datei nicht mehr dem PDF/A-Standard entspricht.") + "\n\n" +
            Lng.T("Das Aktivieren selbst ändert die Datei noch nicht. Erst wenn du eine Bearbeitung ausführst (Seiten löschen oder drehen, Metadaten ändern usw.), wird die Datei sofort und ohne Nachfrage gespeichert und verliert dabei die PDF/A-Kennzeichnung – einen gesonderten Speichern-Schritt gibt es in PDFlight nicht."),
            TaskDialogIcon.Warning)) { return; }
        pdfAEditingEnabled = true;
        UpdateUiState();
    }

    /// <summary>Zeigt das Dateiformat in der Statusleiste: die PDF/A-Stufe, sonst die PDF-Version;
    /// bei unlesbaren (z.B. verschlüsselten) Dateien bleibt das Label ausgeblendet.</summary>
    private void UpdateFormatLabel()
    {
        var pdfA = currentPdfStatus?.PdfALevel;
        statusFormat.Text = pdfA != null ? "PDF/A-" + pdfA : "PDF " + currentPdfStatus?.Version;
        statusFormat.ToolTipText = pdfA != null
            ? Lng.T("PDF/A: Format für die Langzeitarchivierung") + $" (PDF {currentPdfStatus!.Version})"
            : Lng.T("PDF-Version der angezeigten Datei");
        statusFormat.Visible = currentPdfStatus?.Version != null;
    }

    private void OpenFile()
    {
        using OpenFileDialog dialog = new() { Filter = Lng.T("PDF-Dateien (*.pdf)|*.pdf"), Title = Lng.T("PDF-Datei öffnen") };
        if (currentFile != null) { dialog.InitialDirectory = currentFile.DirectoryName; }
        if (dialog.ShowDialog(this) == DialogResult.OK) { LoadPdf(dialog.FileName, addToRecent: true); }
    }

    /// <summary>Dropdown des Öffnen-Buttons: die zuletzt geöffneten Dateien.</summary>
    private void BtnOpen_DropDownOpening(object? sender, EventArgs e)
    {
        settings.ReloadSharedLists();
        if (settings.RecentFiles.RemoveAll(f => !File.Exists(f)) > 0) { settings.Save(); } // verschwundene Dateien gleich austragen statt sie auszugrauen
        btnOpen.DropDownItems.Clear();
        foreach (var file in settings.RecentFiles)
        {
            ToolStripMenuItem item = new(file.Replace("&", "&&")) // voller Pfad, wie im Verschieben-Dropdown
            {
                Tag = file,
                Image = ShellInfo.GetTypeIcon(".pdf", LogicalToDeviceUnits(16)),
            };
            item.Click += (s, args) => LoadPdf((string)((ToolStripMenuItem)s!).Tag!, addToRecent: true);
            btnOpen.DropDownItems.Add(item);
        }
        if (btnOpen.DropDownItems.Count == 0)
        {
            var hint = settings.MaxRecentFiles == 0 ? Lng.T("(Verlauf in den Einstellungen abgeschaltet)") : Lng.T("(keine zuletzt geöffneten Dateien)");
            btnOpen.DropDownItems.Add(new ToolStripMenuItem(hint) { Enabled = false });
        }
        else
        {
            btnOpen.DropDownItems.Add(new ToolStripSeparator());
            ToolStripMenuItem clear = new(Lng.T("Liste leeren")) { Image = MenuIcon(ToolbarIcons.Clear) };
            clear.Click += (s, args) => { settings.RecentFiles.Clear(); settings.Save(); };
            btnOpen.DropDownItems.Add(clear);
        }
    }

    /// <summary>Klassisches Drag &amp; Drop für Formular, Tool- und Statusleiste;
    /// Drops auf das Viewer-Areal fängt PdfViewHost über die file://-Navigation ab.</summary>
    private void EnableClassicDragDrop()
    {
        AllowDrop = true;
        DragEnter += HandleDragEnter;
        DragDrop += HandleDragDrop;
        toolStrip.AllowDrop = true;
        toolStrip.DragEnter += HandleDragEnter;
        toolStrip.DragDrop += HandleDragDrop;
        statusStrip.AllowDrop = true;
        statusStrip.DragEnter += HandleDragEnter;
        statusStrip.DragDrop += HandleDragDrop;
    }

    private void HandleDragEnter(object? sender, DragEventArgs e)
    {
        e.Effect = GetDroppedPdfs(e).Count > 0 ? DragDropEffects.Copy : DragDropEffects.None;
    }

    private void HandleDragDrop(object? sender, DragEventArgs e)
    {
        OpenDroppedFiles(GetDroppedPdfs(e));
    }

    private static List<string> GetDroppedPdfs(DragEventArgs e)
    {
        if (e.Data?.GetDataPresent(DataFormats.FileDrop) == true && e.Data.GetData(DataFormats.FileDrop) is string[] files)
        {
            return [.. files.Where(f => f.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase) && File.Exists(f))];
        }
        return [];
    }

    /// <summary>Verteilt abgelegte Dateien: solange hier nichts angezeigt wird, übernimmt diese Instanz
    /// die erste Datei; jede weitere — und bei bereits angezeigtem Dokument jede — öffnet eine neue
    /// Instanz, damit das aktuelle Dokument nie ungefragt ersetzt wird.</summary>
    private void OpenDroppedFiles(List<string> files)
    {
        if (files.Count == 0) { return; }
        var index = 0;
        if (currentFile == null) { LoadPdf(files[0], addToRecent: true); index = 1; }
        else if (files.Count == 1 && string.Equals(files[0], currentFile.FullName, StringComparison.OrdinalIgnoreCase))
        {
            LoadPdf(files[0]); index = 1;
        } // dieselbe Datei erneut abgelegt → nur neu laden statt zweiter Instanz
        for (; index < files.Count; index++)
        {
            try { Process.Start(Application.ExecutablePath, [files[index]]); }
            catch (Exception ex) when (ex is System.ComponentModel.Win32Exception or InvalidOperationException)
            {
                TaskDlg.ErrTaskDlg(Handle, Lng.T("Das Programm konnte nicht gestartet werden."), ex);
                break;
            }
        }
        Activate();
    }

    /// <summary>Blättert zur nächsten/vorherigen PDF-Datei im Ordner (mit Umlauf, wie in PDFMover).</summary>
    private string? previousFolder; // Quellordner des letzten Verschiebens — fürs Blättern (Dialog wie in PDFMover)

    private void StepFile(int step)
    {
        if (currentFile == null) { return; }
        var folder = currentFile.DirectoryName!;
        // Nach einem Verschieben: im Zielordner weiterblättern oder zurück in den bisherigen Ordner? (wie in PDFMover)
        if (previousFolder != null && Directory.Exists(previousFolder) && !string.Equals(previousFolder, folder, StringComparison.OrdinalIgnoreCase))
        {
            TaskDialogButton btnPrevious = new TaskDialogCommandLinkButton(Lng.T("Vorheriger Ordner:"), previousFolder);
            TaskDialogButton btnCurrent = new TaskDialogCommandLinkButton(Lng.T("Aktueller Ordner:"), folder);
            TaskDialogPage page = new()
            {
                Caption = Application.ProductName,
                Heading = string.Format(Lng.T("Du möchtest die {0} Datei öffnen."), step > 0 ? Lng.T("nächste") : Lng.T("vorherige")) + Environment.NewLine + Lng.T("Welcher Ordner soll durchsucht werden?"),
                AllowCancel = true,
                SizeToContent = true,
                Buttons = { btnPrevious, btnCurrent, TaskDialogButton.Cancel },
                DefaultButton = btnPrevious
            };
            var result = TaskDialog.ShowDialog(Handle, page);
            if (result == btnPrevious)
            {
                var target = previousFolder;
                previousFolder = null;
                StepFileInFolder(target, step);
                return;
            }
            if (result != btnCurrent) { return; } // Abbrechen (auch Esc): nichts passiert, die Frage bleibt fürs nächste Blättern bestehen
            previousFolder = null;
        }
        StepFileInFolder(folder, step);
    }

    /// <summary>Blättert im angegebenen Ordner; liegt die aktuelle Datei dort nicht (mehr),
    /// wird sie virtuell einsortiert, damit das Blättern an ihrer alten Position ansetzt.</summary>
    private void StepFileInFolder(string folder, int step)
    {
        var files = FileUtil.GetPdfFilesInFolder(folder);
        var reference = Path.Combine(folder, currentFile!.Name);
        var index = files.FindIndex(f => string.Equals(f, reference, StringComparison.OrdinalIgnoreCase));
        if (index < 0)
        {
            if (files.Count == 0)
            {
                TaskDlg.MsgTaskDlg(Handle, Lng.T("Der Ordner enthält keine PDF-Dateien."), folder, TaskDialogIcon.Information);
                return;
            }
            files.Add(reference);
            FileUtil.SortNatural(files);
            index = files.FindIndex(f => string.Equals(f, reference, StringComparison.OrdinalIgnoreCase));
        }
        var next = (index + step + files.Count) % files.Count;
        if (next == index || string.Equals(files[next], currentFile.FullName, StringComparison.OrdinalIgnoreCase)) { return; }
        var pid = InstanceRegistry.FindInstanceShowing(files[next]);
        if (pid == null) { LoadPdf(files[next]); return; }
        // Die Zieldatei steht schon in einem anderen Fenster — nachfragen statt sie doppelt anzuzeigen
        var alternative = FindFreeFile(files, next, step, currentFile.FullName);
        var choice = TaskDlg.OpenConflictTaskDlg(Handle, step > 0 ? Lng.T("Die nächste Datei ist bereits geöffnet") : Lng.T("Die vorherige Datei ist bereits geöffnet"),
            files[next], Lng.T("Dieses Fenster zeigt weiter die aktuelle Datei."), Lng.T("Datei überspringen"), alternative, restorePath: null, offerExit: false);
        if (choice == TaskDlg.ConflictChoice.Activate && !InstanceRegistry.Activate(pid.Value)) { LoadPdf(files[next]); } // das andere Fenster ist inzwischen weg → hier anzeigen
        else if (choice == TaskDlg.ConflictChoice.Alternative) { LoadPdf(alternative!); } // Alternative wird nur mit Pfad angeboten
    }

    /// <summary>Nach dem Löschen: nächste Datei an gleicher Position laden oder Anzeige leeren. Zeigt eine
    /// andere Instanz die nachrückende Datei bereits an, entscheidet ein Dialog, wie es weitergeht.</summary>
    private void LoadNextAfterRemoval(List<string> files, int removedIndex)
    {
        if (removedIndex >= 0) { files.RemoveAt(removedIndex); } else { removedIndex = 0; }
        if (files.Count == 0) { ClearDisplay(Lng.T("Der Ordner enthält keine weiteren PDF-Dateien.")); return; }
        var nextIndex = removedIndex % files.Count;
        var next = files[nextIndex];
        var pid = InstanceRegistry.FindInstanceShowing(next);
        if (pid == null) { LoadPdf(next); return; }
        var alternative = FindFreeFile(files, nextIndex, 1, null);
        var restorePath = undoAction?.Kind == UndoKind.Delete ? undoAction.TargetFile : null; // Wiederherstellen nur mit Papierkorb-Eintrag
        currentFile = null; // sonst meldet MainForm_Activated nach dem Dialog die gelöschte Datei als extern verschwunden
        switch (TaskDlg.OpenConflictTaskDlg(Handle, Lng.T("Die nächste Datei ist bereits geöffnet"), next, Lng.T("Dieses Fenster bleibt leer."),
            Lng.T("Nächste freie Datei anzeigen"), alternative, restorePath, offerExit: true))
        {
            case TaskDlg.ConflictChoice.Activate:
                if (InstanceRegistry.Activate(pid.Value)) { ClearDisplay(Lng.T("Die Datei wurde in den Papierkorb verschoben.")); }
                else { LoadPdf(next); } // das andere Fenster ist inzwischen weg → hier anzeigen
                break;
            case TaskDlg.ConflictChoice.Alternative: LoadPdf(alternative!); break; // Alternative wird nur mit Pfad angeboten
            case TaskDlg.ConflictChoice.Undo: UndoLastChange(); break;
            case TaskDlg.ConflictChoice.Exit: Close(); break;
            default: ClearDisplay(Lng.T("Die Datei wurde in den Papierkorb verschoben.")); break; // Abbruch: leer, Strg+Z holt die Datei zurück
        }
    }

