    // Die ersten vier Einträge des Zoomfelds sind benannte Stufen (Reihenfolge wie im Designer), danach folgen Prozentwerte
    private static readonly PageFit[] NamedFits = [PageFit.Page, PageFit.Height, PageFit.Width];
