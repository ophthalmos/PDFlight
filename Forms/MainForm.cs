    private void ComboZoom_SelectedIndexChanged(object? sender, EventArgs e)
    {
        if (updatingZoomBox) { return; }
        var index = comboZoom.SelectedIndex;
        if (index >= 0 && index < NamedFits.Length) { pageView.SetFit(NamedFits[index]); }
        else if (index == OriginalSizeEntry) { pageView.SetZoom(1f, null); } // 100 % = Originalgröße: ein Punkt ist 1/72 Zoll auf dem Bildschirm
        else { ApplyZoomText(comboZoom.Text); }
        BeginInvoke(() => UpdateZoomDisplay()); // die Auswahl schreibt ihren Listentext erst nach dem Ereignis ins Feld – danach wieder die Prozentzahl
    }

