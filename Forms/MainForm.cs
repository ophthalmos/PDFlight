    /// <summary>Öffnet eine Webadresse im Standardprogramm – nur http, https und mailto (keine Dateien, Programme oder Skripte).</summary>
    private void OpenUri(string uri)
    {
        if ((!Uri.TryCreate(uri.Trim(), UriKind.Absolute, out var parsed) && !Uri.TryCreate("https://" + uri.Trim(), UriKind.Absolute, out parsed))
            || parsed.Scheme is not ("http" or "https" or "mailto"))
        {
            statusPath.Text = string.Format(Lng.T("Dieser Link wird nicht geöffnet: {0}"), uri);
            return;
        }
        try { Process.Start(new ProcessStartInfo(parsed.AbsoluteUri) { UseShellExecute = true }); }
        catch (System.ComponentModel.Win32Exception ex) { TaskDlg.ErrTaskDlg(Handle, Lng.T("Der Link konnte nicht geöffnet werden."), ex); }
    }

