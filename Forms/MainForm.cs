        // nur Optionen anbieten, die etwas liefern; bleibt allein der Dateidialog, erscheint er ohne Zwischenfrage (Wunsch vom 20.09.2026)
        List<(int Kind, string Text, string? Detail)> choices = [(0, Lng.T("Einzelne Datei auswählen"), Lng.T("Über den Dateidialog"))];
        if (shown.Count > 0) { choices.Add((1, Lng.T("Geöffnete Dateien hinzufügen"), Lng.T("In anderen Instanzen angezeigte PDF-Dateien"))); }
        if (siblings.Count > 0) { choices.Add((2, Lng.T("Dateien desselben Ordners"), Lng.T("PDF-Dateien aus dem Ordner der angezeigten Datei"))); }
        var choice = 0;
        if (choices.Count > 1)
        {
            var picked = TaskDlg.ChoiceTaskDlg(Handle, Lng.T("Was soll angehängt werden?"), null, [.. choices.Select(c => (c.Text, c.Detail))]);
            if (picked < 0) { return; }
            choice = choices[picked].Kind;
        }
        List<string> files;
        switch (choice)
        {
            case 0:
                using (OpenFileDialog dialog = new() { Filter = Lng.T("PDF-Dateien (*.pdf)|*.pdf"), Title = Lng.T("PDF-Datei anhängen"), InitialDirectory = currentFile.DirectoryName })
                {
                    if (dialog.ShowDialog(this) != DialogResult.OK) { return; }
                    if (string.Equals(dialog.FileName, file, StringComparison.OrdinalIgnoreCase))
                    {
                        TaskDlg.MsgTaskDlg(Handle, Lng.T("Die Datei kann nicht an sich selbst angehängt werden."), null, TaskDialogIcon.Warning);
                        return;
                    }
                    files = [dialog.FileName];
                }
                break;
            case 1:
            case 2:
                using (FileListForm list = new(choice == 1 ? Lng.T("Geöffnete PDF-Dateien") : string.Format(Lng.T("PDF-Dateien im Ordner „{0}“"), currentFile.Directory?.Name), choice == 1 ? shown : siblings))
                {
                    if (list.ShowDialog(this) != DialogResult.OK || list.SelectedFiles.Count == 0) { return; }
                    files = list.SelectedFiles;
                }
                break;
            default: return;
        }
        var firstNewPage = currentPageCount + 1;
        var totalPages = 0;
        if (RunPdfEdit(() => totalPages = PdfEditService.AppendPdfs(file, files), Lng.T("Anhängen")))
        {
            LoadPdf(file, firstNewPage);
            statusPath.Text = files.Count == 1 ? string.Format(Lng.T("\"{0}\" wurde angehängt."), Path.GetFileName(files[0])) : string.Format(Lng.T("{0} Dateien wurden angehängt."), files.Count);
            var added = totalPages - firstNewPage + 1;
            ShowSplash(added == 1 ? Lng.T("1 Seite angehängt") : string.Format(Lng.T("{0} Seiten angehängt"), added)); // die Anzeige ändert sich sonst kaum sichtbar (Wunsch vom 20.09.2026)
        }
    }

