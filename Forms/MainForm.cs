    private void UpdateViewerLayout()
    {
        if (viewerStrip.Items.Count == 0 || updatingViewerLayout) { return; }
        updatingViewerLayout = true;
        try { LayoutViewerStrip(); }
        finally { updatingViewerLayout = false; }
